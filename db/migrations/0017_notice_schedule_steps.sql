-- 0017 — 공고 일정 흐름도의 나머지 단계 (SH 첨부 「입주자 모집 절차 및 일정」, S3)
--
-- 지금까지는 흐름도에서 접수 시작·마감·당첨자 발표 세 날짜만 꺼내 썼다. 그런데 흐름도에는
-- 「서류심사 대상자 발표」·「서류심사 대상자 서류 제출」·「계약 체결」이 같이 그려져 있고,
-- 신청자에게는 이쪽이 더 급한 날짜다 — 서류를 제때 못 내면 발표까지 갈 일이 없다
-- (사용자 지적 2026-09-09: "서류심사대상자 발표일이 빠졌던데").
--
-- 단계 구성이 공고 유형마다 다르다(장기전세는 순위별 접수, 미리내집은 사전 주택공개가 붙는다).
-- 칸을 고정으로 파면 유형이 늘 때마다 마이그레이션이 필요하므로 순서 있는 JSON 배열로 둔다.
-- 형식: [{"label": "서류 제출", "start": "2026-09-28", "end": "2026-09-30"}] — end는 하루짜리면 null.
ALTER TABLE notice ADD COLUMN schedule_steps jsonb;
COMMENT ON COLUMN notice.schedule_steps IS
  'SH 첨부 일정 흐름도에서 읽은 접수·발표 외 단계. [{label,start,end}] 순서 배열. end가 null이면 하루';
