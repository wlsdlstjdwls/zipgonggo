export type GuideBlock =
  /** 가구원수별 소득 한도 막대. pcts는 그릴 비율 */
  | { kind: "income"; pcts: number[] }
  /** 예비입주자 대기현황을 유형별로 */
  | { kind: "waitlist-type" }
  /** 예비입주자 대기현황을 시도별로 */
  | { kind: "waitlist-sido" }
  /** 단지 형별 기본 보증금과 월임대료 중앙값 */
  | { kind: "rent-type" }
  /** 행복주택 기본 금액 중앙값으로 전환 한도 끝까지 밀어 본 세 조합 */
  | { kind: "convert" }
  /** SH 결과 공고 경쟁률 */
  | { kind: "competition" }
  /** 기관별 공고 일정 간격 */
  | { kind: "schedule" }
  /** 자격 시드 비교표. cls가 있으면 그 계층을 받는 공급유형만, cols는 보일 기준 */
  | { kind: "seeds"; cls?: string; cols: ("age" | "marital" | "income" | "asset" | "car" | "homeless" | "region")[] }
  /** 지금 진행 중인 공고를 유형별로 */
  | { kind: "open-types" };

