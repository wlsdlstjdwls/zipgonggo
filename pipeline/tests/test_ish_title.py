"""i-sh 게시판 제목 → 유형 분류 회귀. 실제 게시판 449건에서 뽑은 제목만 쓴다."""

import pytest

from zipgonggo_pipeline.parsers.ish_title import derive_housing_type, is_notice


@pytest.mark.parametrize("title", [
    "제51차 장기전세주택 입주자 모집공고(2026.08.31.공고)",
    "2020년 1차 행복주택 모집 공고(2020. 6. 25.)",
    "2020년 1차 역세권청년주택(공공임대) 입주자모집 공고",
    "2026년 사당동 공공원룸 잔여세대 입주자모집공고(26. 1.30.)",
])
def test_real_notices(title):
    assert is_notice(title)


@pytest.mark.parametrize("title", [
    # 모집공고 제목을 통째로 인용한 발표문 — 유형 키워드가 다 들어 있어 제일 위험하다
    "2025년 미리내집 연계형 공공한옥 입주자 모집공고(2025. 12. 30.) 예비 3차 당첨자 발표",
    "제37차 장기전세주택 모집공고(19.07.31.) 예비4차 입주대상자 발표",
    # 주택 공급이 아닌 것
    "마곡지구 17단지 토지임대부 분양주택 입주자모집공고",
    "2026년 1차 임대상가 재공급 모집공고",
    "상암지구 7단지 분양아파트 입주자 모집 공고문",
    "2026년 제1차 보증금지원형 장기안심주택 입주자 모집공고",
    "가든파이브 웍스 아파트형공장 입주자 모집공고",
])
def test_not_a_notice(title):
    assert not is_notice(title)


@pytest.mark.parametrize("title,expected", [
    ("제51차 장기전세주택 입주자 모집공고", "장기전세"),
    ("2025년 미리내집 연계형 공공한옥 입주자 모집공고", "장기전세"),      # 미리내집은 장기전세 브랜드
    ("3차 시프트 입주자 모집공고", "장기전세"),
    ("SHift (발산3단지, 신월동도센트리움) 입주자 모집공고", "장기전세"),   # 대소문자 섞인 표기
    ("2020년 1차 행복주택 모집 공고", "행복주택"),
    ("2020년 1차 역세권청년주택(공공임대) 입주자모집 공고", "청년안심주택"),
    ("2026년 성북구 연극인주택 잔여세대 입주자 모집공고", "매입임대"),
    ("2026년 가양동 육아 협동조합주택(이음채) 잔여세대 입주자 모집공고", "매입임대"),
    ("2023년 1차 공공전세주택 신규 입주자 모집공고", "매입임대"),
    ("2026년 신내의료안심주택 잔여세대 입주자모집공고", "매입임대"),
    ("2020년 공공·주거환경임대주택 입주자 모집공고", "재개발임대"),
    ("2026년 국민임대주택 입주자 모집공고", "국민임대"),
    ("희망하우징 입주자 모집공고", "공공기숙사"),
])
def test_housing_type(title, expected):
    assert derive_housing_type(title) == expected


def test_ambiguous_returns_none():
    """못 가리면 None. 억지로 붙이면 slug가 굳어 되돌릴 수 없다."""
    assert derive_housing_type("고덕강일 공공주택지구 8, 14단지 입주자모집공고") is None
    assert derive_housing_type("[리모델링 매입형 사회주택] 아츠스테이 신림(안테나) 최초 입주자 모집공고") is None


def test_cheongnyeon_beats_maeip():
    """역세권청년주택은 매입임대 규칙보다 먼저 잡혀야 한다(둘 다 걸리는 제목이 있다)."""
    assert derive_housing_type("2020년 1차 역세권청년주택(공공임대) 매입 입주자모집 공고") == "청년안심주택"
