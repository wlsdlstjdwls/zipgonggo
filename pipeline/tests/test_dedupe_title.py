"""정정 표지 떼기. 헐거우면 남남인 공고가 한 덩이로 묶인다 — 여기가 그 안전선이다."""

from zipgonggo_pipeline.normalize import base_title, is_amendment, title_key


def test_앞에_붙은_표지를_뗀다():
    assert base_title("(수정) 2026년 2차 장기미임대 매입임대주택 입주자모집공고(2026. 8. 28.)") == \
        "2026년 2차 장기미임대 매입임대주택 입주자모집공고(2026. 8. 28.)"
    assert base_title("[수정공고]신내의료안심주택(일반공급) 잔여세대 입주자 모집공고") == \
        "신내의료안심주택(일반공급) 잔여세대 입주자 모집공고"
    assert base_title("[2022.01.14.수정]2021년 2차 행복주택 입주자 모집 공고(2021.12.28.공고)") == \
        "2021년 2차 행복주택 입주자 모집 공고(2021.12.28.공고)"


def test_뒤에_붙은_표지도_뗀다():
    assert base_title("제31차 장기전세주택 입주자 모집공고(수정게시)") == "제31차 장기전세주택 입주자 모집공고"
    assert base_title("2018년 제2차 국민임대주택 모집공고(수정)") == "2018년 제2차 국민임대주택 모집공고"
    assert base_title("신혼부부 대상 도시형생활주택 추가입주자 모집(2015.7.15.)_수정게시") == \
        "신혼부부 대상 도시형생활주택 추가입주자 모집(2015.7.15.)"


def test_정정_말이_없는_괄호는_건드리지_않는다():
    # 「(잔여공가)」「(2026. 8. 28.)」는 제목의 일부다. 떼면 서로 다른 공고가 같은 열쇠를 갖는다
    t = "2020년 재개발임대주택(잔여공가) 일반공급 입주자 모집공고(2020.12.03.)"
    assert base_title(t) == t
    assert not is_amendment(t)


def test_꼬리에_붙은_정정_사유는_표지로_본다():
    # 「…모집공고(인터넷 청약 시작일 변경, 청약방법 정정)」는 원 공고 제목에 사유를 덧붙인 꼴이다.
    # 같은 기관·같은 게시일이라는 조건이 함께 걸리므로 떼어 원 공고와 묶는 편이 맞다
    t = "2020년 재개발임대주택(잔여공가) 일반공급 입주자 모집공고(인터넷 청약 시작일 변경, 청약방법 정정)"
    assert base_title(t) == "2020년 재개발임대주택(잔여공가) 일반공급 입주자 모집공고"
    assert is_amendment(t)


def test_표지만_다른_두_제목은_같은_열쇠다():
    a = "(수정) 2026년 2차 장기미임대 매입임대주택 입주자모집공고(2026. 8. 28.)"
    b = "2026년 2차 장기미임대 매입임대주택 입주자모집공고(2026.8.28.)"
    assert title_key(a) == title_key(b)
    assert is_amendment(a) and not is_amendment(b)


def test_너무_짧아지면_되돌린다():
    # 「(정정공고)」만 남는 제목을 빈 문자열로 만들지 않는다
    assert base_title("(정정공고)") == "(정정공고)"
